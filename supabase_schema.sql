-- =============================================================================
-- BrandShield AI - Supabase PostgreSQL Production Schema
-- Compatible with PostgreSQL 15+ and Supabase Data API (PostgREST)
-- =============================================================================

-- Enable UUID extension
CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- -----------------------------------------------------------------------------
-- 1. Table: brands (Corporate Brand Protection Registry)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.brands (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    official_handles JSONB NOT NULL DEFAULT '[]'::jsonb,
    official_domains JSONB NOT NULL DEFAULT '[]'::jsonb,
    verified_developers JSONB NOT NULL DEFAULT '[]'::jsonb,
    category TEXT DEFAULT 'Enterprise',
    description TEXT DEFAULT '',
    is_demo BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Performance Indexes on brand registry
CREATE INDEX IF NOT EXISTS idx_brands_name ON public.brands (name);
CREATE INDEX IF NOT EXISTS idx_brands_created_at ON public.brands (created_at DESC);

-- -----------------------------------------------------------------------------
-- 2. Table: scans (Multi-Vector Digital Risk Protection Audit Log)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.scans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_type TEXT NOT NULL CHECK (scan_type IN ('link', 'social', 'app')),
    target_brand_id BIGINT REFERENCES public.brands(id) ON DELETE SET NULL,
    target_brand_name TEXT,
    input_title TEXT NOT NULL,
    input_details JSONB NOT NULL DEFAULT '{}'::jsonb,
    risk_score INTEGER NOT NULL CHECK (risk_score >= 0 AND risk_score <= 100),
    risk_category TEXT NOT NULL,
    summary_reason TEXT NOT NULL,
    indicators JSONB NOT NULL DEFAULT '[]'::jsonb,
    recommendations JSONB NOT NULL DEFAULT '[]'::jsonb,
    api_findings JSONB DEFAULT '{}'::jsonb,
    evidence JSONB DEFAULT '{}'::jsonb,
    ml_findings JSONB DEFAULT '{}'::jsonb,
    profile_ml_findings JSONB DEFAULT '{}'::jsonb,
    app_ml_findings JSONB DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Performance Indexes for Dashboard Aggregates & History Filtering
CREATE INDEX IF NOT EXISTS idx_scans_created_at ON public.scans (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_scans_scan_type ON public.scans (scan_type);
CREATE INDEX IF NOT EXISTS idx_scans_risk_category ON public.scans (risk_category);
CREATE INDEX IF NOT EXISTS idx_scans_target_brand_id ON public.scans (target_brand_id);
CREATE INDEX IF NOT EXISTS idx_scans_risk_score ON public.scans (risk_score DESC);

-- -----------------------------------------------------------------------------
-- 3. Table: vt_cache (VirusTotal & Threat Intelligence Persistent Cache)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.vt_cache (
    cache_key TEXT PRIMARY KEY,
    cache_type TEXT NOT NULL,
    response_json JSONB NOT NULL,
    status TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_vt_cache_created_at ON public.vt_cache (created_at DESC);

-- =============================================================================
-- 4. ROW LEVEL SECURITY (RLS) POLICIES
-- Strict Security Requirement: RLS is active on all tables.
-- Server backend using the secret API key bypasses RLS safely.
-- Read access is permitted for application views.
-- =============================================================================

ALTER TABLE public.brands ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.scans ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.vt_cache ENABLE ROW LEVEL SECURITY;

-- Brands RLS Policies
DROP POLICY IF EXISTS "Allow select brands" ON public.brands;
CREATE POLICY "Allow select brands" ON public.brands FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow modify brands" ON public.brands;
CREATE POLICY "Allow modify brands" ON public.brands FOR ALL USING (true) WITH CHECK (true);

-- Scans RLS Policies
DROP POLICY IF EXISTS "Allow select scans" ON public.scans;
CREATE POLICY "Allow select scans" ON public.scans FOR SELECT USING (true);

DROP POLICY IF EXISTS "Allow insert scans" ON public.scans;
CREATE POLICY "Allow insert scans" ON public.scans FOR INSERT WITH CHECK (true);

DROP POLICY IF EXISTS "Allow modify scans" ON public.scans;
CREATE POLICY "Allow modify scans" ON public.scans FOR ALL USING (true) WITH CHECK (true);

-- VirusTotal Threat Cache RLS Policies
DROP POLICY IF EXISTS "Allow all vt_cache" ON public.vt_cache;
CREATE POLICY "Allow all vt_cache" ON public.vt_cache FOR ALL USING (true) WITH CHECK (true);
